def fit_tail(xk):
    """Gain (0 to 1) and time constant with which the velocity of the last 0.5 s best predicted this path's own next
    5 s, over cuts at every earlier second. Returns (0, 0.35), a hold, when the file is too short."""
    cuts = np.arange(100, len(xk) - 50, 10)
    if len(cuts) < 5:
        return 0.0, 0.35
    sj = np.arange(5, 51, 5)
    v = (xk[cuts] - xk[cuts - 5]) * 2.0
    d = np.stack([xk[cuts + j] - xk[cuts] for j in sj], 1)
    best = (np.inf, 0.0, 0.35)
    for tau in (0.35, 0.7, 1.5, 3.0):
        a = tau * (1 - np.exp(-(sj * 0.1) / tau))
        num = (a[None, :] * (d * v[:, None, :]).sum(2)).sum()
        den = (a[None, :] ** 2 * (v ** 2).sum(1)[:, None]).sum()
        G = float(np.clip(num / max(den, 1e-12), 0.0, 1.0))
        err = ((d - G * a[None, :, None] * v[:, None, :]) ** 2).sum()
        if err < best[0]:
            best = (err, G, tau)
    return best[1], best[2]


def run(t_ns, imu, C=None):
    C = C or pickle.load(open(CONST_PY, "rb"))
    P = prepare(t_ns, imu)
    drone = is_drone(P["t"], P["imu"], P["ok"])
    cal = np.asarray(C["b0"]) if drone else np.zeros(3)
    tb_, mb = hardened_rest(P["t"], P["imu"], P["ok"])
    b0 = cal
    if tb_ is not None:
        rest = np.median(mb, 0)
        b0 = cal if np.linalg.norm(rest - cal) < 0.02 else rest
    elif drone:
        # no rest period: keep the declared calibration only if the file agrees with it across the up direction
        bw, Nw, nw = wbias(P["t"], P["imu"][:, :3], P["imu"][:, 3:], P["ok"])
        up = P["imu"][P["ok"], 3:].mean(0)
        up /= np.linalg.norm(up)
        if nw >= 5 and np.linalg.norm((bw - cal) - ((bw - cal) @ up) * up) >= 0.03:
            b0 = bw - (bw @ up) * up
    m77.VARIANT.clear()
    m77.VARIANT.update(dict(lever=True, fc=0.2, k=C["k"], r=C["r"], d=C["d"]))
    q, v, tb, last, info, ec, shift = rwe.run_solver(P, b0, 8.0, 0.5, 0.05, pen="rw", eb_passes=1, kappa=1.0)
    d = to_cache(q, v, tb, info["drone"])
    # self-check: fall back to the high-pass when the slow speed is implausible, or, on a drone, when the evidence
    # chose a fast accel drift (over RATE_LIMIT) while the slow speed is over 0.6 of its limit (87_selfcheck.py)
    c0 = CFG2[0] if d["drone"] else CFG2[1]
    slow = m57.slow_rms(d)
    fell = slow > c0 or (d["drone"] and info["sig_a_final"] > RATE_LIMIT and slow > 0.6 * c0)
    vf = m58.final_v(d, C["fit"], -1.0, -1.0, CFG2[2], CFG2[3]) if fell else m58.final_v(d, C["fit"], *CFG2)
    tr = m57.track(P, d, vf)
    tail = P["t"] > d["tk"][-1]
    s = P["t"][tail] - d["tk"][-1]
    if fell and d["drone"]:
        # a drone solve that was not trusted: carry no velocity into the blind tail
        tr[tail] = np.cumsum(vf, axis=0)[-1] * DT
    elif not d["drone"]:
        # handheld: the file chooses its own tail gain and time constant from its own path (85_tail_lab.py)
        xk = np.cumsum(vf, axis=0) * DT
        G, tau = fit_tail(xk)
        v0 = vf[-5:].mean(0)
        tr[tail] = xk[-1] + G * tau * (1 - np.exp(-s / tau))[:, None] * v0[None]
    if d["drone"]:
        L = P["last_good"]
        fs = round(1.0 / np.median(np.diff(P["t"])))
        idx = np.arange(len(P["t"]))
        a = np.stack([np.interp(idx, idx[P["ok"]], P["imu"][P["ok"], 3 + i]) for i in range(3)], 1)
        on = rotors_on(a, fs)
        if on[max(0, L - int(2.0 * fs)): L + 1].mean() > 0.5:
            tr[tail, 2] -= DESCENT * np.minimum(s / DESCENT_T, 1.0)
    th = 0.5 * np.pi * np.minimum(s / 5.0, 1.0)
    tr[tail, 0] += CURVE_R * (np.cos(th) - 1.0)
    tr[tail, 1] += CURVE_R * np.sin(th)
    keep = P["ids"] != -1
    return P["t_ns"][keep], tr[keep], q[keep], dict(drone=bool(d["drone"]), b0=b0, slow=m57.slow_rms(d), P=P, d=d, q_all=q, tr_all=tr)


def write_tum(path, t_ns, p, q_wxyz):
    with open(path, "w") as f:
        f.write("# timestamp tx ty tz qx qy qz qw\n")
        for t, pp, qq in zip(t_ns, p, q_wxyz):
            f.write(f"{int(t) // 10**9}.{int(t) % 10**9:09d} {pp[0]:.6f} {pp[1]:.6f} {pp[2]:.6f} {qq[1]:.9f} {qq[2]:.9f} {qq[3]:.9f} {qq[0]:.9f}\n")


def test_files():
    out = []
    for n in SEQS:
        for k in (("clean", "delete", 1), ("full", "zero", 1), ("rot", "x", 1), ("hold", "x", 1), ("sine", "x", 1)):
            out.append((n, k))
    for n in DEV_ROOMS:
        for k in (("clean", "delete", 1), ("full", "zero", 1), ("rot", "x", 1), ("noisy", "x", 1), ("sine", "x", 1)):
            out.append((n, k))
    return out


def tname(n, k):
    return f"{n if isinstance(n, str) else 'room%d' % n}_{k[0]}"


def make_test(job):
    n, k = job
    base = f"{TESTS}/{tname(n, k)}"
    if not os.path.exists(base + ".csv"):
        t, imu, room = m72.file_for2(n, k)
        common.write_csv(base + ".csv", t, imu)
    if not os.path.exists(base + "_py.txt"):
        t, imu = common._read_csv_ns(base + ".csv")
        tt, p, q, info = run(t, imu)
        write_tum(base + "_py.txt", tt, p, q)
    return job


